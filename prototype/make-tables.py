def char_to_palette(c):
    if c == ' ':
        return 0
    elif c == '.':
        return 1
    elif c == ':':
        return 2
    elif c == '#':
        return 3
    else:
        assert False

def palette_to_rgb(i):
    if i == 0:
        return (0, 0, 0)
    elif i == 1:
        return (255, 0, 0)
    elif i == 2:
        return (255, 255, 0)
    elif i == 3:
        return (255, 255, 255)
    else:
        assert False

def char_to_rgb(c):
    return palette_to_rgb(char_to_palette(c))

def string_to_rgb(s):
    assert len(s) == 4
    return [char_to_rgb(c) for c in s]

def string_to_palette(s):
    assert len(s) == 4
    return [char_to_palette(c) for c in s]

def intensity(rgb):
    return rgb[0] * 0.2989 + rgb[1] * 0.5870 + rgb[2] * 0.1140

def screen_byte(a, b, c, d):
    assert 0 <= a <= 3
    assert 0 <= b <= 3
    assert 0 <= c <= 3
    assert 0 <= d <= 3

    def bits(x):
        return ((x & 2) << 3) | (x & 1)

    return (bits(a) << 3) | (bits(b) << 2) | (bits(c) << 1) | bits(d)

def string_to_screen_byte(s):
    return screen_byte(*(string_to_palette(s)))

